// Embeds supabase/functions/album/public/** into a generated TS module.
// Necessary because Supabase's function deploy bundler does not ship the
// public/ directory as loose files at runtime (confirmed empirically — see
// the comment in supabase/functions/album/lib/staticFiles.ts) — only files
// reachable through the module import graph make it into the deployed
// bundle. Run this before every `supabase functions deploy album`.
//
//   node scripts/build-assets.js

const fs = require("fs");
const path = require("path");

const root = path.join(__dirname, "..", "supabase", "functions", "album", "public");
const outDir = path.join(__dirname, "..", "supabase", "functions", "album", "assets");
const outFile = path.join(outDir, "generated.ts");

function walk(dir, base) {
  const out = {};
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    const full = path.join(dir, entry.name);
    const rel = base ? `${base}/${entry.name}` : entry.name;
    if (entry.isDirectory()) {
      Object.assign(out, walk(full, rel));
    } else {
      out[rel.split(path.sep).join("/")] = fs.readFileSync(full, "utf8");
    }
  }
  return out;
}

const files = walk(root, "");
const entries = Object.entries(files)
  .sort(([a], [b]) => a.localeCompare(b))
  .map(([relPath, content]) => `  ${JSON.stringify(relPath)}: ${JSON.stringify(content)},`)
  .join("\n");

const header = `// AUTO-GENERATED by scripts/build-assets.js from public/** — do not hand-edit.
// Edit the source files under supabase/functions/album/public/ instead, then
// re-run \`node scripts/build-assets.js\` before deploying.

export const ASSETS: Record<string, string> = {
${entries}
};
`;

fs.mkdirSync(outDir, { recursive: true });
fs.writeFileSync(outFile, header);
console.log(`Wrote ${Object.keys(files).length} files into ${path.relative(process.cwd(), outFile)}`);
